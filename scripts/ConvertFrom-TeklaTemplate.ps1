<#
.SYNOPSIS
    Convert a Tekla Template Editor file (.tpl / .rpt) to its JSON intermediate
    representation (IR) — the machine-editable form of the template.

.DESCRIPTION
    Parses the template with the skill's shared parser and serializes the parse
    tree as JSON: nested { block, id, props, children } objects. The JSON is the
    authoring format for the deterministic pipeline

        JSON (schema-validated)  --ConvertTo-TeklaTemplate.ps1-->  .tpl / .rpt

    Values map naturally: numbers stay numbers, quoted strings stay strings,
    bare enum keywords (justify = LEFT) become plain JSON strings, TRUE/FALSE
    become JSON booleans, tuples become arrays. Whether a JSON string is
    re-emitted bare or quoted is decided canonically from the corpus kind census
    in assets\template-grammar.json; for the rare value whose source form
    disagrees with that decision, this script writes an explicit
    {"ident": "X"} / {"string": "X"} override so the round trip is lossless BY
    CONSTRUCTION. Validate the output against assets\template-schema.json
    (generated by New-TeklaTemplateSchema.ps1) with Test-Json.

.PARAMETER Path
    The .tpl or .rpt file to convert.

.PARAMETER Out
    Output JSON path. Default: "<input>.json" next to the input.
    (skeleton_part_list.rpt -> skeleton_part_list.rpt.json)

.PARAMETER GrammarFile
    Kind census / allow-list JSON (default: assets\template-grammar.json next to
    the skill). Regenerate per Tekla version with Get-TeklaGrammar.ps1.

.PARAMETER PassThru
    Also write the JSON text to stdout.

.EXAMPLE
    scripts\ConvertFrom-TeklaTemplate.ps1 assets\skeleton_part_list.rpt
    # -> assets\skeleton_part_list.rpt.json

.EXAMPLE
    scripts\ConvertFrom-TeklaTemplate.ps1 my.tpl -PassThru | ConvertFrom-Json
#>
[CmdletBinding()]
param(
    [Parameter(Mandatory)][string] $Path,
    [string] $Out,
    [string] $GrammarFile,
    [switch] $PassThru
)

$ErrorActionPreference = 'Stop'
. "$PSScriptRoot\_TemplateParser.ps1"
. "$PSScriptRoot\_TemplateIR.ps1"

if (-not (Test-Path $Path -PathType Leaf)) { throw "File not found: $Path" }
$Path = (Resolve-Path $Path).Path
if (-not $Out) { $Out = "$Path.json" }

$table = Get-TeklaKindTable -GrammarFile $GrammarFile
$text = [System.IO.File]::ReadAllText($Path)
$root = Parse-Template -Text $text
$ir = ConvertTo-TeklaIRNode -Node $root -Table $table
$json = ConvertTo-TeklaIRJson -Ir $ir

[System.IO.File]::WriteAllText($Out, $json, (New-Object System.Text.UTF8Encoding($false)))

$blocks = @(Get-AllBlocks $root).Count
[Console]::Error.WriteLine("Wrote $Out  ($blocks blocks)")
if ($PassThru) { $json }
