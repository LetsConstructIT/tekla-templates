<#
.SYNOPSIS
    Deterministically emit a Tekla Template Editor file (.tpl / .rpt) from its
    JSON intermediate representation (IR). The safe way to CREATE templates:
    author (or generate) JSON, validate it against the schema, and let this
    script produce canonical template text that Template Editor can open.

.DESCRIPTION
    Pipeline stage:  JSON IR  ->  [JSON Schema check]  ->  canonical .tpl/.rpt

    The emitter's output layout is FIXED (the layout TplEd itself writes): CRLF
    line endings, a leading blank line, 4-space indentation, one statement per
    line, '{' and '};' on their own lines, a blank line before each child block,
    no comments. Every known TplEd crash class — packed statements, inline '{',
    structural comments, bare-LF endings — is therefore unreachable by
    construction. The same JSON always yields byte-identical output.

    Three verification gates run in order:
      1. JSON Schema validation (Test-Json against assets\template-schema.json,
         when present; skip with -NoSchema) — block nesting, property names,
         enum values, value types.
      2. Re-parse: the emitted text is parsed back with the skill's parser; the
         script fails (writing nothing) if it does not parse.
      3. Optional -Strict: the grammar allow-list check + TplEd portability lint
         (same checks as Render-TeklaTemplate.ps1 -Strict).

    JSON value forms: number -> bare number; true/false -> TRUE/FALSE; array ->
    tuple; string -> bare enum keyword or quoted string, decided canonically
    from the corpus kind census (justify = LEFT vs name = "x"); to force a form,
    use {"ident": "X"} or {"string": "X"}.

.PARAMETER Path
    The IR JSON file to emit. (Or pass raw JSON text via -Json.)

.PARAMETER Json
    Raw IR JSON text (alternative to -Path, e.g. from a pipeline).

.PARAMETER Out
    Output template path. Default: input path minus its ".json" suffix
    (my.tpl.json -> my.tpl); if that leaves no .tpl/.rpt extension, one is
    derived from props.type (GRAPHICAL -> .tpl, otherwise .rpt).

.PARAMETER SchemaFile
    JSON Schema to validate against (default: assets\template-schema.json next
    to the skill; generated by New-TeklaTemplateSchema.ps1).

.PARAMETER NoSchema
    Skip the JSON Schema gate (gate 2, the re-parse, always runs).

.PARAMETER GrammarFile
    Kind census / allow-list JSON (default: assets\template-grammar.json).

.PARAMETER Strict
    Also run the grammar allow-list check and TplEd portability lint on the
    emitted text; findings go to stderr and set a nonzero exit code.

.PARAMETER PassThru
    Also write the emitted template text to stdout.

.EXAMPLE
    scripts\ConvertTo-TeklaTemplate.ps1 my_report.rpt.json -Strict
    # JSON -> schema check -> my_report.rpt, then grammar-lint the result

.EXAMPLE
    scripts\ConvertFrom-TeklaTemplate.ps1 a.rpt; scripts\ConvertTo-TeklaTemplate.ps1 a.rpt.json -Out b.rpt
    # round trip: a.rpt -> JSON -> b.rpt (b is the canonical form of a)
#>
[CmdletBinding()]
param(
    [Parameter(Position = 0)][string] $Path,
    [string] $Json,
    [string] $Out,
    [string] $SchemaFile,
    [switch] $NoSchema,
    [string] $GrammarFile,
    [switch] $Strict,
    [switch] $PassThru
)

$ErrorActionPreference = 'Stop'
. "$PSScriptRoot\_TemplateParser.ps1"
. "$PSScriptRoot\_TemplateIR.ps1"
. "$PSScriptRoot\_TemplateGrammar.ps1"

if (-not $Path -and -not $Json) { throw "Pass -Path <ir.json> or -Json <text>." }
if ($Path) {
    if (-not (Test-Path $Path -PathType Leaf)) { throw "File not found: $Path" }
    $Path = (Resolve-Path $Path).Path
    $Json = [System.IO.File]::ReadAllText($Path)
}

# --- gate 1: JSON Schema -----------------------------------------------------
if (-not $SchemaFile) { $SchemaFile = Join-Path (Split-Path $PSScriptRoot -Parent) 'assets\template-schema.json' }
if (-not $NoSchema) {
    if (Test-Path $SchemaFile) {
        $schemaErr = $null
        $ok = Test-Json -Json $Json -SchemaFile $SchemaFile -ErrorAction SilentlyContinue -ErrorVariable schemaErr
        if (-not $ok) {
            [Console]::Error.WriteLine("SCHEMA: the IR JSON does not conform to $SchemaFile :")
            foreach ($e in $schemaErr) { [Console]::Error.WriteLine("  # $($e.Exception.Message)") }
            throw "Schema validation failed — nothing was written. (Bypass with -NoSchema only if you know the schema is stale.)"
        }
    }
    else {
        [Console]::Error.WriteLine("SCHEMA: $SchemaFile not found — skipping (generate it with scripts\New-TeklaTemplateSchema.ps1).")
    }
}

$ir = Read-TeklaIRJson -JsonText $Json
$table = Get-TeklaKindTable -GrammarFile $GrammarFile
$text = ConvertTo-TeklaTemplateText -Ir $ir -Table $table

# --- gate 2: the emitted text MUST re-parse ----------------------------------
try { $root = Parse-Template -Text $text }
catch { throw "Internal emitter error — output does not re-parse: $($_.Exception.Message)" }

# --- resolve output path -----------------------------------------------------
if (-not $Out) {
    if ($Path -and $Path -like '*.json') { $Out = $Path.Substring(0, $Path.Length - 5) }
    elseif ($Path) { $Out = $Path }
    else { $Out = 'template' }
    if ($Out -notmatch '\.(tpl|rpt)$') {
        $type = if ($ir['props'] -and $ir['props']['type']) { [string]$ir['props']['type'] } else { '' }
        $Out += if ($type -eq 'GRAPHICAL') { '.tpl' } else { '.rpt' }
    }
}

[System.IO.File]::WriteAllText($Out, $text, (New-Object System.Text.UTF8Encoding($false)))
$blocks = @(Get-AllBlocks $root).Count
[Console]::Error.WriteLine("Wrote $Out  ($blocks blocks, $(($text -split "`r`n").Count) lines)")

# --- gate 3 (optional): grammar allow-list + TplEd portability lint ----------
$exit = 0
if ($Strict) {
    $any = Write-StrictValidation -Root $root -GrammarFile $GrammarFile -Text $text
    if ($any) { $exit = 2 }
}
if ($PassThru) { $text }
exit $exit
